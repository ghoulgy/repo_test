#!/usr/bin/env node

const fs = require('fs');
const os = require('os');
const path = require('path');

const homeDirectory = os.homedir();

const desktopPath = path.join(homeDirectory, 'Downloads');

const filePath = path.join(desktopPath, 'test.txt');

const fileContent = "Hello! This file was generated by a Node.js script.\n";

try {
    console.log(`Attempting to create file at: ${filePath}`);
    
    fs.writeFileSync(filePath, fileContent, 'utf8');
    
    console.log("Success! The file test.txt has been created on your Desktop.");
} catch (error) {
    console.error("Failed to create the file. See error below:");
    console.error(error.message);
}
