#!/usr/bin/env node

const fs = require('fs');
const os = require('os');
const path = require('path');

// 1. Get the current user's home directory
const homeDirectory = os.homedir();

// 2. Construct the path to the Desktop folder
// Note: This assumes the standard English folder name "Desktop"
const desktopPath = path.join(homeDirectory, 'Desktop');

// 3. Construct the full path for the new file
const filePath = path.join(desktopPath, 'test.txt');

// 4. The content you want to write inside the file
const fileContent = "Hello! This file was generated by a Node.js script.\n";

// 5. Execute the file creation
try {
    console.log(`Attempting to create file at: ${filePath}`);
    
    // writeFileSync creates the file, or overwrites it if it already exists
    fs.writeFileSync(filePath, fileContent, 'utf8');
    
    console.log("Success! The file test.txt has been created on your Desktop.");
} catch (error) {
    console.error("Failed to create the file. See error below:");
    console.error(error.message);
}
